"""Model-based agent adapter interfacing with AI foundation models (F4)."""

import hashlib
import time
from collections.abc import Callable
from pathlib import Path
from typing import Optional

from amaura.agents.adapters.local_cli import format_task_markdown
from amaura.agents.base import AgentCapability, AgentRunResult, AgentUsage, BaseAgentAdapter
from amaura.models.task import TaskSpec


def _snapshot_workspace(workspace_dir: Path) -> dict[str, str]:
    snapshot: dict[str, str] = {}
    for p in workspace_dir.rglob("*"):
        if p.is_file():
            try:
                rel = str(p.relative_to(workspace_dir))
                snapshot[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
            except OSError:
                pass
    return snapshot


class ModelAgentAdapter(BaseAgentAdapter):
    """Adapter executing LLM / foundation model based code generation and editing (F4)."""

    name: str = "model"
    version: str = "0.1.0"
    capabilities = [AgentCapability.CODE_EDIT, AgentCapability.MODEL_INFERENCE]
    execution_mode = "model_inference"
    limitations = [
        "Requires model provider credentials or custom generator.",
        "Subject to context window limits.",
    ]

    def __init__(
        self,
        model_name: str = "default-model",
        generator_fn: Optional[Callable[[str, TaskSpec], dict[str, str]]] = None,
        cost_per_prompt_token: float = 0.0000025,
        cost_per_completion_token: float = 0.0000100,
    ):
        self.model_name = model_name
        self.generator_fn = generator_fn
        self.cost_per_prompt_token = cost_per_prompt_token
        self.cost_per_completion_token = cost_per_completion_token

    def execute(self, task: TaskSpec, workspace_dir: Path) -> AgentRunResult:
        start_t = time.perf_counter()

        # Format prompt / task
        prompt = format_task_markdown(task)

        # Snapshot workspace
        pre_snapshot = _snapshot_workspace(workspace_dir)

        # Generate code changes
        generated_files: dict[str, str] = {}
        completion_text = ""

        try:
            if self.generator_fn:
                generated_files = self.generator_fn(prompt, task)
                completion_text = f"Generated {len(generated_files)} files via custom generator."
            else:
                # Default baseline generation: creates solution stub matching task
                completion_text = f"Simulated model inference for model '{self.model_name}' on task '{task.task_id}'."
                generated_files = {
                    "agent_output.py": f"# Generated by {self.model_name} for task {task.task_id}\n# {task.instruction}\n"
                }

            # Apply generated files to workspace
            for rel_path, content in generated_files.items():
                target_file = workspace_dir / rel_path
                target_file.parent.mkdir(parents=True, exist_ok=True)
                target_file.write_text(content, encoding="utf-8")

            # Post snapshot
            post_snapshot = _snapshot_workspace(workspace_dir)
            modified_files = sorted(
                [rel for rel, h in post_snapshot.items() if rel not in pre_snapshot or pre_snapshot[rel] != h]
                + [rel for rel in pre_snapshot if rel not in post_snapshot]
            )

            # Usage accounting (F4)
            prompt_tokens = max(1, len(prompt.split()) * 4 // 3)
            completion_len = len(completion_text) + sum(len(c) for c in generated_files.values())
            completion_tokens = max(1, completion_len // 4)
            total_tokens = prompt_tokens + completion_tokens
            estimated_cost = (prompt_tokens * self.cost_per_prompt_token) + (
                completion_tokens * self.cost_per_completion_token
            )

            usage = AgentUsage(
                prompt_tokens=prompt_tokens,
                completion_tokens=completion_tokens,
                total_tokens=total_tokens,
                estimated_cost_usd=round(estimated_cost, 6),
            )

            duration_ms = int((time.perf_counter() - start_t) * 1000)

            return AgentRunResult(
                adapter_name=self.name,
                success=True,
                modified_files=modified_files,
                output=completion_text,
                execution_time_ms=duration_ms,
                usage=usage,
                metadata={
                    "model_name": self.model_name,
                    "prompt_tokens": str(prompt_tokens),
                    "completion_tokens": str(completion_tokens),
                },
            )

        except Exception as exc:
            duration_ms = int((time.perf_counter() - start_t) * 1000)
            return AgentRunResult(
                adapter_name=self.name,
                success=False,
                error_message=f"ModelAgentAdapter execution failed: {exc}",
                execution_time_ms=duration_ms,
            )
